export type AgentKnowledgeEntry = {
  title: string;
  description: string;
  content: string;
  responses: {
    saveEmail: string;
    addTag: string;
    setStatus: string;
  };
};

export const AGENT_KNOWLEDGE: Record<string, AgentKnowledgeEntry> = {
  userData: {
    title: 'Данные пользователя',
    description: 'Блок для изменения данных в профиле пользователя',
    content: `Блок «Данные пользователя» используется для изменения данных в профиле пользователя.

Он позволяет:
- добавлять и удалять теги
- устанавливать и сбрасывать статус
- записывать и очищать значения в полях профиля

Когда использовать:
- чтобы сохранить ответ пользователя
- чтобы записать email, телефон, имя
- чтобы отметить пользователя тегом
- чтобы изменить статус

Когда не использовать:
- если нужно получить ответ → используйте «Ввод»
- если нужно отправить сообщение → используйте «Сообщение»
- если нужно временное значение → используйте «Переменная»

Как работает:
Сначала выбирается, что изменить.
Потом выбирается действие.
Потом указывается значение (если требуется).

Связка блоков:
Сообщение → Ввод → Данные пользователя

{{input}} — это ответ пользователя из блока «Ввод».

Пример сохранения email:
Что изменить? → Поле пользователя
Действие → Записать
Поле → email
Новое значение → {{input}}

Важно:
«Новое значение» — это то, что будет записано в профиль пользователя.

Агент должен:
- использовать только реальные названия полей
- объяснять пошагово
- не использовать технические термины
- не придумывать поля

Агент НЕ должен:
- путать блок с «Ввод»
- говорить, что блок получает ответ
- использовать старые поля
- использовать внутренние ключи`,
    responses: {
      saveEmail: `Используйте блок «Данные пользователя»:

Что изменить? → Поле пользователя
Действие → Записать
Поле → email
Новое значение → {{input}}`,

      addTag: `Что изменить? → Тег
Действие → Добавить
Тег → нужное значение`,

      setStatus: `Что изменить? → Статус
Действие → Установить
Статус → нужное значение`,
    },
  },
};

export function getAgentKnowledgeByKey(key: string): AgentKnowledgeEntry | null {
  return AGENT_KNOWLEDGE[key] ?? null;
}
