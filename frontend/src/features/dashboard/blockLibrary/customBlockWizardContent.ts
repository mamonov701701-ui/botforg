export function customBlockWizardStepNumber(id: string): number {
  const index = CUSTOM_BLOCK_WIZARD_STEPS.findIndex(step => step.id === id);
  if (index < 0) throw new Error(`Unknown custom block wizard step: ${id}`);
  return index + 1;
}

